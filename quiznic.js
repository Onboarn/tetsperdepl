const questionEl = document.getElementById('question');
const answerListEl = document.getElementById('answer-list');
const submitBtn = document.getElementById('submit');
const counterEl = document.getElementById('quiz-counter');
const barFillEl = document.getElementById('quiz-bar-fill');

let currentQuiz = 0;
let score = 0;
let answered = false;

function updateProgress(done) {
    counterEl.textContent = `Вопрос ${currentQuiz + 1} из ${quizData.length}`;
    barFillEl.style.width = (done / quizData.length * 100) + '%';
}

function loadQuiz() {
    answered = false;
    answerListEl.classList.remove('answered');
    submitBtn.textContent = 'Ответить';
    updateProgress(currentQuiz);

    const current = quizData[currentQuiz];
    questionEl.textContent = current.question.replace(/^\d+\.\s*/, '');
    answerListEl.innerHTML = '';

    current.answers.forEach((text, idx) => {
        const li = document.createElement('li');
        const input = document.createElement('input');
        const label = document.createElement('label');

        input.type = 'radio';
        input.name = 'answer';
        input.id = 'ans' + idx;
        input.value = idx;

        label.htmlFor = input.id;
        label.textContent = text;

        li.append(input, label);
        answerListEl.appendChild(li);
    });
}

function getSelected() {
    const checked = answerListEl.querySelector('input[name="answer"]:checked');
    return checked ? Number(checked.value) : undefined;
}

answerListEl.addEventListener('change', (e) => {
    if (e.target.name !== 'answer') return;
    answerListEl.querySelectorAll('li').forEach(li => li.classList.remove('selected'));
    e.target.closest('li').classList.add('selected');
});

function showResult() {
    document.getElementById('quiz').innerHTML = `
        <div class="quiz-complete">
            <h2>Правильных ответов: ${score} из ${quizData.length}</h2>
            <button class="restart-btn" id="restart">Пройти заново</button>
        </div>
    `;
    document.getElementById('restart').addEventListener('click', () => location.reload());
}

function goNext() {
    currentQuiz++;
    if (currentQuiz < quizData.length) {
        loadQuiz();
    } else {
        showResult();
    }
}

submitBtn.addEventListener('click', () => {
    if (answered) {
        goNext();
        return;
    }

    const answer = getSelected();

    if (answer === undefined) {
        alert('Пожалуйста, выберите вариант ответа!');
        return;
    }

    answered = true;
    const correct = quizData[currentQuiz].correct;

    if (answer === correct) score++;

    answerListEl.classList.add('answered');
    answerListEl.querySelectorAll('li').forEach((li, idx) => {
        li.querySelector('input').disabled = true;
        if (idx === correct) {
            li.classList.add('correct');
        } else if (idx === answer) {
            li.classList.add('wrong');
        }
    });

    updateProgress(currentQuiz + 1);
    submitBtn.textContent = currentQuiz === quizData.length - 1 ? 'Показать результат' : 'Следующий вопрос';
});

